//! Supervision of the wayvnc subprocess.
//!
//! wayvnc is launched with a Unix-domain listener inside the private runtime
//! directory, so it never binds a network port. Its generated config file
//! holds the session password and lives at mode 0600 beside the socket.

use crate::identity::Identity;
use crate::ipc::AccessMode;
use crate::paths;
use crate::secret::Secret;
use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::time::Duration;
use tokio::io::{AsyncBufReadExt, AsyncReadExt, AsyncWriteExt, BufReader};
use tokio::net::UnixStream;
use tokio::process::{Child, Command};

/// How long to wait for wayvnc to create its listening socket.
const STARTUP_TIMEOUT: Duration = Duration::from_secs(10);
const POLL_INTERVAL: Duration = Duration::from_millis(50);

/// How long to wait for wayvnc's control socket to answer a `client-list`.
const CONTROL_TIMEOUT: Duration = Duration::from_secs(2);

#[derive(Debug)]
pub struct Wayvnc {
    child: Child,
    /// Path to the Unix socket carrying the VNC protocol.
    pub vnc_socket: PathBuf,
    /// wayvnc's own JSON control socket, for `wayvncctl`.
    pub control_socket: PathBuf,
    config_file: PathBuf,
}

/// Render the wayvnc config file.
///
/// `enable_auth` requires a password *and* a certificate/key pair; wayvnc
/// refuses to start otherwise. No `address`/`port` keys are emitted, so there
/// is no path by which wayvnc could end up with a TCP listener.
pub fn render_config(username: &str, password: &Secret, identity: &Identity) -> String {
    format!(
        "# Generated by swayshare. Rewritten on every session; do not edit.\n\
         enable_auth=true\n\
         username={username}\n\
         password={password}\n\
         certificate_file={cert}\n\
         private_key_file={key}\n",
        username = username,
        password = password.expose(),
        cert = identity.cert_path.display(),
        key = identity.key_path.display(),
    )
}

/// Build wayvnc's argument list.
///
/// Separate from the spawn so the one security-relevant decision here - that
/// `--disable-input` is present for a view-only session and absent otherwise -
/// can be asserted directly. wayvnc reads this flag only at startup, which is
/// why the access mode is fixed for the life of a session.
pub fn command_args(
    config_file: &Path,
    control_socket: &Path,
    vnc_socket: &Path,
    mode: AccessMode,
) -> Vec<std::ffi::OsString> {
    let mut args: Vec<std::ffi::OsString> = vec![
        "--unix-socket".into(),
        "--config".into(),
        config_file.into(),
        "--socket".into(),
        control_socket.into(),
        "--log-level=info".into(),
    ];
    if mode.is_view_only() {
        args.push("--disable-input".into());
    }
    // The listening address must come last: it is positional.
    args.push(vnc_socket.into());
    args
}

impl Wayvnc {
    /// Start wayvnc and wait until its socket is accepting connections.
    pub async fn spawn(
        runtime_dir: &Path,
        username: &str,
        password: &Secret,
        identity: &Identity,
        mode: AccessMode,
    ) -> Result<Self> {
        Self::spawn_program("wayvnc", runtime_dir, username, password, identity, mode).await
    }

    /// Start a specific program as the capture backend.
    ///
    /// Exists so the failure paths can be tested with a program that is
    /// guaranteed not to exist; production always goes through [`Wayvnc::spawn`].
    pub async fn spawn_program(
        program: &str,
        runtime_dir: &Path,
        username: &str,
        password: &Secret,
        identity: &Identity,
        mode: AccessMode,
    ) -> Result<Self> {
        let vnc_socket = runtime_dir.join("vnc.sock");
        let control_socket = runtime_dir.join("wayvnc.sock");
        let config_file = runtime_dir.join("wayvnc.conf");

        // wayvnc refuses to bind an existing path; clear leftovers from a
        // previous run that did not shut down cleanly.
        paths::remove_if_present(&vnc_socket);
        paths::remove_if_present(&control_socket);

        paths::write_private(&config_file, &render_config(username, password, identity))
            .context("writing the wayvnc session config")?;

        // From here on, every error path must erase the config file again:
        // it holds the session password in plaintext.
        let result = Self::launch(
            program,
            config_file.clone(),
            vnc_socket,
            control_socket,
            mode,
        )
        .await;
        if result.is_err() {
            paths::remove_if_present(&config_file);
        }
        result
    }

    /// Spawn the process and wait for its socket. Split out so its many error
    /// paths all funnel through the credential cleanup above.
    async fn launch(
        program: &str,
        config_file: PathBuf,
        vnc_socket: PathBuf,
        control_socket: PathBuf,
        mode: AccessMode,
    ) -> Result<Self> {
        let mut cmd = Command::new(program);
        cmd.args(command_args(
            &config_file,
            &control_socket,
            &vnc_socket,
            mode,
        ))
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        // If the daemon dies unexpectedly, wayvnc must not outlive it.
        .kill_on_drop(true);

        let mut child = cmd.spawn().map_err(|e| {
            if e.kind() == std::io::ErrorKind::NotFound {
                anyhow::anyhow!(
                    "{program} not found on PATH. On NixOS try: nix shell nixpkgs#wayvnc"
                )
            } else {
                anyhow::Error::new(e).context(format!("spawning {program}"))
            }
        })?;

        // wayvnc's diagnostics are the only clue when capture fails, so
        // forward them to our own log rather than discarding them.
        if let Some(stderr) = child.stderr.take() {
            tokio::spawn(async move {
                let mut lines = BufReader::new(stderr).lines();
                while let Ok(Some(line)) = lines.next_line().await {
                    eprintln!("[wayvnc] {line}");
                }
            });
        }

        let mut this = Self {
            child,
            vnc_socket,
            control_socket,
            config_file,
        };
        if let Err(e) = this.await_socket().await {
            // Never leave a half-started wayvnc or its password file behind.
            this.shutdown().await;
            return Err(e);
        }
        Ok(this)
    }

    /// Poll until the VNC socket accepts a connection, or wayvnc exits.
    async fn await_socket(&mut self) -> Result<()> {
        let deadline = tokio::time::Instant::now() + STARTUP_TIMEOUT;
        loop {
            if let Some(status) = self.child.try_wait().context("polling wayvnc")? {
                bail!(
                    "wayvnc exited during startup with {status}. \
                     Is this a wlroots compositor with WAYLAND_DISPLAY set? \
                     See the [wayvnc] lines above."
                );
            }
            // Existence is not enough: the socket file appears before listen(2).
            if tokio::net::UnixStream::connect(&self.vnc_socket)
                .await
                .is_ok()
            {
                return Ok(());
            }
            if tokio::time::Instant::now() >= deadline {
                bail!(
                    "wayvnc did not start listening on {} within {}s",
                    self.vnc_socket.display(),
                    STARTUP_TIMEOUT.as_secs()
                );
            }
            tokio::time::sleep(POLL_INTERVAL).await;
        }
    }

    /// Resolve when wayvnc exits on its own, so the daemon can fail closed.
    pub async fn wait(&mut self) -> std::io::Result<std::process::ExitStatus> {
        self.child.wait().await
    }

    /// Number of VNC clients that have completed authentication.
    ///
    /// See the free [`authenticated_clients`] function for why this is not the
    /// same as the number of connected clients.
    pub async fn authenticated_clients(&self) -> Result<usize> {
        authenticated_clients(&self.control_socket).await
    }

    /// Stop wayvnc and erase the session credentials from disk.
    ///
    /// SIGKILL rather than SIGTERM: revocation has to be immediate, and wayvnc
    /// has no state worth flushing.
    pub async fn shutdown(&mut self) {
        let _ = self.child.start_kill();
        let _ = self.child.wait().await;
        paths::remove_if_present(&self.config_file);
        paths::remove_if_present(&self.vnc_socket);
        paths::remove_if_present(&self.control_socket);
    }
}

/// Count the VNC clients that have *authenticated*, via wayvnc's control socket.
///
/// wayvnc reports a client - both in its `client-connected` event and in
/// `client-list` - the instant the TCP connection is accepted, before any
/// password has been checked. The access gate sees the same thing: a bare TCP
/// connect, indistinguishable from a port scan or a viewer that will fail the
/// password. So "connected" on its own cannot answer the question that matters,
/// which is whether someone is actually in.
///
/// `client-list` is the one place that can: it fills in a client's `username`
/// only once that client has passed authentication. neatvnc's only encrypted
/// security type here is VeNCrypt X509-Plain, which always carries a username,
/// so a non-empty `username` is an exact, reliable marker of an authenticated
/// session. We count those.
pub async fn authenticated_clients(control_socket: &Path) -> Result<usize> {
    let clients = client_list(control_socket).await?;
    Ok(clients
        .iter()
        .filter(|c| {
            c.get("username")
                .and_then(|u| u.as_str())
                .is_some_and(|u| !u.is_empty())
        })
        .count())
}

/// Fetch wayvnc's current client list over its JSON control socket.
///
/// The protocol is one JSON request object in, one JSON response object back
/// (`{"code":0,"data":[...]}`); there is no framing beyond "a complete JSON
/// value", so we read until the buffer parses. A whole second query is cheaper
/// to reason about than a long-lived event subscription, and the daemon only
/// calls this while a client is connected.
async fn client_list(control_socket: &Path) -> Result<Vec<serde_json::Value>> {
    let fut = async {
        let mut stream = UnixStream::connect(control_socket)
            .await
            .context("connecting to the wayvnc control socket")?;
        stream
            .write_all(br#"{"method":"client-list"}"#)
            .await
            .context("sending client-list to wayvnc")?;

        let mut buf = Vec::with_capacity(512);
        let mut chunk = [0u8; 512];
        loop {
            // A complete object may already be buffered; try before blocking.
            if let Some(value) = try_parse_object(&buf) {
                return Ok(value);
            }
            let n = stream
                .read(&mut chunk)
                .await
                .context("reading the wayvnc client-list reply")?;
            if n == 0 {
                // EOF: parse whatever arrived, or report the truncation.
                return try_parse_object(&buf)
                    .context("wayvnc closed the control socket mid-reply");
            }
            buf.extend_from_slice(&chunk[..n]);
        }
    };

    let response: serde_json::Value = tokio::time::timeout(CONTROL_TIMEOUT, fut)
        .await
        .context("wayvnc control socket did not answer in time")??;

    match response.get("data") {
        // `data` is the array for a successful client-list.
        Some(serde_json::Value::Array(clients)) => Ok(clients.clone()),
        // An error reply, or a shape we do not recognise: treat as no clients
        // rather than tearing down a working session over a transient blip.
        _ => Ok(Vec::new()),
    }
}

/// Parse one complete JSON object from `buf`, or `None` if it is still partial.
fn try_parse_object(buf: &[u8]) -> Option<serde_json::Value> {
    if buf.is_empty() {
        return None;
    }
    match serde_json::from_slice::<serde_json::Value>(buf) {
        Ok(value) => Some(value),
        Err(e) if e.is_eof() => None,
        // Malformed (not just incomplete): nothing more to wait for.
        Err(_) => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn test_identity() -> Identity {
        Identity {
            cert_path: PathBuf::from("/run/user/1000/swayshare/cert.pem"),
            key_path: PathBuf::from("/run/user/1000/swayshare/key.pem"),
            fingerprint: "AA:BB".into(),
        }
    }

    #[test]
    fn config_enables_auth_with_all_required_keys() {
        let pw = Secret::generate().unwrap();
        let text = render_config("support", &pw, &test_identity());
        assert!(text.contains("enable_auth=true"));
        assert!(text.contains("username=support"));
        assert!(text.contains(&format!("password={}", pw.expose())));
        assert!(text.contains("certificate_file=/run/user/1000/swayshare/cert.pem"));
        assert!(text.contains("private_key_file=/run/user/1000/swayshare/key.pem"));
    }

    fn args_for(mode: AccessMode) -> Vec<String> {
        command_args(
            Path::new("/run/u/swayshare/wayvnc.conf"),
            Path::new("/run/u/swayshare/wayvnc.sock"),
            Path::new("/run/u/swayshare/vnc.sock"),
            mode,
        )
        .into_iter()
        .map(|a| a.to_string_lossy().into_owned())
        .collect()
    }

    #[test]
    fn view_only_disables_input_and_control_does_not() {
        let view = args_for(AccessMode::ViewOnly);
        assert!(
            view.contains(&"--disable-input".to_string()),
            "a view-only session must start wayvnc with --disable-input: {view:?}"
        );
        let control = args_for(AccessMode::Control);
        assert!(
            !control.contains(&"--disable-input".to_string()),
            "a control session must not disable input: {control:?}"
        );
    }

    #[test]
    fn the_socket_path_stays_positional_and_last() {
        // wayvnc takes the listen address positionally; a flag inserted after
        // it would be read as the address instead.
        for mode in [AccessMode::Control, AccessMode::ViewOnly] {
            let args = args_for(mode);
            assert_eq!(
                args.last().map(String::as_str),
                Some("/run/u/swayshare/vnc.sock"),
                "the socket path must be the final argument for {mode}"
            );
        }
    }

    #[test]
    fn both_modes_still_use_a_unix_socket_and_our_config() {
        for mode in [AccessMode::Control, AccessMode::ViewOnly] {
            let args = args_for(mode);
            assert!(args.contains(&"--unix-socket".to_string()));
            assert!(args.contains(&"/run/u/swayshare/wayvnc.conf".to_string()));
        }
    }

    #[tokio::test]
    async fn a_failed_launch_leaves_no_password_on_disk() {
        let dir = std::env::temp_dir().join(format!("swayshare-spawn-{}", std::process::id()));
        paths::ensure_private_dir(&dir).unwrap();
        let conf = dir.join("wayvnc.conf");
        let pw = Secret::generate().unwrap();

        let err = Wayvnc::spawn_program(
            "swayshare-no-such-capture-backend",
            &dir,
            "support",
            &pw,
            &test_identity(),
            AccessMode::Control,
        )
        .await
        .expect_err("a missing backend must not report success");
        assert!(err.to_string().contains("not found on PATH"), "got: {err}");

        assert!(
            !conf.exists(),
            "the session config holds the password in plaintext and must be erased"
        );
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn only_clients_with_a_username_count_as_authenticated() {
        // A reply mixing an authenticated client (has a username) with a bare
        // connection (no username yet) must count exactly one.
        let reply = br#"{"code":0,"data":[
            {"id":"1","address":"10.0.0.3","username":"support"},
            {"id":"2","address":"10.0.0.3"},
            {"id":"3","address":"10.0.0.3","username":""}
        ]}"#;
        let response = try_parse_object(reply).expect("a complete reply must parse");
        let clients = match response.get("data") {
            Some(serde_json::Value::Array(c)) => c.clone(),
            other => panic!("expected a data array, got {other:?}"),
        };
        let authed = clients
            .iter()
            .filter(|c| {
                c.get("username")
                    .and_then(|u| u.as_str())
                    .is_some_and(|u| !u.is_empty())
            })
            .count();
        assert_eq!(authed, 1, "only the client with a non-empty username is in");
    }

    #[test]
    fn a_partial_reply_is_not_yet_an_object() {
        // The leading half of an object must read as "keep waiting", not an
        // error and not a premature parse.
        assert!(try_parse_object(br#"{"code":0,"data":["#).is_none());
        assert!(try_parse_object(b"").is_none());
        assert!(try_parse_object(br#"{"code":0,"data":[]}"#).is_some());
    }

    #[test]
    fn config_never_requests_a_network_listener() {
        let pw = Secret::generate().unwrap();
        let text = render_config("support", &pw, &test_identity());
        for line in text.lines().filter(|l| !l.starts_with('#')) {
            let key = line.split('=').next().unwrap_or_default();
            assert_ne!(key, "address", "wayvnc must never bind a TCP address");
            assert_ne!(key, "port", "wayvnc must never bind a TCP port");
        }
    }
}
